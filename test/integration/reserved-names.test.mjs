import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { test } from 'node:test';

import { compile, flush, mount, rt, root } from './harness.mjs';

const header = '// @generated by jinge-compiler intl-compile';
for (const [name, source] of [
  ['variable', 'const $jg$=1;'],
  ['generated setter', 'let $jg$v=1;'],
  ['suffix', 'const attrs$jg$=1;'],
  ['middle', 'const each$jg$0=1;'],
  ['function', 'function read$jg$(){}'],
  ['parameter', 'function f($jg$props){}'],
  ['destructured binding', 'const {name:$jg$name}=data;'],
  ['shorthand binding', 'const {$jg$name}=data;'],
  ['catch binding', 'try{}catch($jg$error){}'],
  ['class', 'class Model$jg$ {}'],
  ['import binding', `import {value as value$jg$} from './other';`],
  ['free reference', 'console.log($jg$free);'],
  ['computed reference', 'const value=data[$jg$key];'],
  ['unused default import', `import value$jg$ from './other';`],
  ['namespace import', `import * as ns$jg$ from './other';`],
  ['runtime enum', 'enum E$jg$ { A }'],
  ['runtime namespace', 'namespace N$jg$ { export const value=1 }'],
  ['object shorthand', 'const value={$jg$free};'],
  ['computed method key', 'const value={[$jg$key](){}};'],
  ['escaped binding', String.raw`const \u0024jg\u0024=1;`],
])
  for (const type of [1, 2])
    test(`S02 reserved ${name} in type ${type}`, () => {
      assert.throws(
        () => compile(source, { type }),
        (error) => {
          assert.match(error.message, /保留.*\$jg\$/);
          assert.match(error.message, /fixture\.tsx?:1:/);
          return true;
        },
      );
    });
for (const [name, source] of [
  [
    'properties and strings',
    `const obj={$jg$:1,$jg$method(){return '$jg$'}};const {$jg$:value}=obj;export const result=obj.$jg$+value;`,
  ],
  [
    'type-only names',
    `type $jg$T=string;interface $jg$I{value:$jg$T}import type {$jg$X} from './other';export const value=1;`,
  ],
  [
    'aliased external names',
    `import {$jg$external as safe} from './other';export {safe as $jg$public};`,
  ],
  ['re-export keys', `export {$jg$external as safe} from './other';`],
  [
    'class keys and implements',
    'interface $jg$I{};class C implements $jg$I { $jg$method(){}; $jg$value=1 }',
  ],
  [
    'erased overload and abstract parameters',
    'function f($jg$arg:string):void;function f(arg:string){};abstract class C {abstract method($jg$arg:string):void}',
  ],
  ['enum member keys', 'enum E { $jg$member=1 }'],
  ['type export specifier', 'type $jg$T=number;export {type $jg$T}'],
  ['ambient types', `declare const $jg$external:string;export const value=1;`],
])
  test(`S02 does not reject ${name}`, () => {
    assert.doesNotThrow(() => compile(source, { type: 1 }));
  });
test('S02 generated dictionary marker allows only the intl props identifier', () => {
  assert.doesNotThrow(() =>
    compile(
      `${header}\nexport default function Message($jg$props){return <p>{$jg$props.name}</p>}`,
    ),
  );
  assert.throws(() => compile(`${header}\nconst $jg$v=1;`), /保留.*\$jg\$/);
  assert.throws(() => compile(`// user source\n${header}\nconst $jg$props=1;`), /保留.*\$jg\$/);
});
test('S02 user JSX props names remain ordinary strings', async () => {
  const view = await mount(
    `export function A(){const obj={$jg$:'value'};return <span title={obj.$jg$}>$jg$</span>}`,
  );
  try {
    assert.equal(view.text(), '$jg$');
    assert.equal(document.querySelector('span').title, 'value');
  } finally {
    view.dispose();
  }
});
test('S02 computed intl key v is not captured by the generated setter', async () => {
  await rt.intlInit({
    defaultLocale: 'reserved',
    dicts: { reserved: { g: (params) => String(params.name) } },
  });
  const view = await mount(
    `import {vm,t} from 'jinge';const v='name';export const state=vm({name:'Ada'});export function A(){return <span>{t('Hello {name}',{[v]:state.name},{key:'g'})}</span>}`,
    { intl: 1 },
  );
  try {
    assert.equal(view.text(), 'Ada');
    view.m.state.name = 'Bob';
    await flush();
    assert.equal(view.text(), 'Bob');
  } finally {
    view.dispose();
  }
});
test('S02 intl generation preserves ordinary props and validates source names', () => {
  const result = spawnSync(
    process.execPath,
    [`${root}/test/.compiled/tools.js`, 'reserved-names'],
    { encoding: 'utf8' },
  );
  assert.equal(result.status, 0, result.stdout + result.stderr);
});
