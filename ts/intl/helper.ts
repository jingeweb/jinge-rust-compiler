import ts from '@typescript/typescript6';
import { type Options, parse } from 'csv-parse/sync';
import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';

import { loadBinding } from '../binding';

export const GENERATED_INTL_HEADER = '// @generated by jinge-compiler intl-compile';
export const GENERATED_INTL_PROPS = '$jg$props';
const validatedSources = new WeakSet<ts.SourceFile>();
export function validateSourceNames(srcFile: ts.SourceFile) {
  if (validatedSources.has(srcFile)) return;
  loadBinding().validateSource(
    srcFile.fileName,
    srcFile.languageVariant === ts.LanguageVariant.JSX ? 2 : 1,
    srcFile.text,
  );
  validatedSources.add(srcFile);
}

/**
 * 计算文本的 hash。需要和 packages/swc-plugin/intl.rs 中使用算法一致，当前统一为 sha512().toBase64().slice(0,6)。
 * 如果修改两处都要变更。
 */
export function calcIntlTextKey(defaultMessage: string, filename?: string) {
  const hasher = createHash('sha512');
  hasher.update(defaultMessage);
  if (filename) {
    hasher.update(filename);
  }
  const hash = hasher.digest('base64');
  return hash.slice(0, 6);
}

export async function loopReadDir(dir: string) {
  const files = await fs.readdir(dir);
  const result: string[] = [];
  for (const f of files) {
    const p = path.join(dir, f);
    const st = await fs.stat(p);
    if (st.isDirectory()) {
      result.push(...(await loopReadDir(p)));
    } else if (st.isFile() && /\.(ts|tsx)$/.test(f) && !f.endsWith('.d.ts')) {
      result.push(p);
    }
  }
  return result;
}

export async function parseCsv(file: string, opts: Options = {}) {
  return parse(await fs.readFile(file, 'utf-8'), {
    columns: true,
    skip_empty_lines: true,
    ...opts,
  });
}

export async function writeCsv(head: string[], rows: Record<string, string>[], file: string) {
  const lines = [
    head.join(','),
    ...rows.map((row) => {
      return head
        .map((k) => {
          let v = row[k];
          if (!v) return '';
          v = v.replaceAll('"', () => '""');
          if (v.includes(',') || v.includes('"') || v.includes('\n') || v.includes('\r'))
            v = `"${v}"`;
          return v;
        })
        .join(',');
    }),
  ];
  await fs.writeFile(file, lines.join('\n'));
}

export function parseExtractArgvs() {
  const cwd = process.cwd();
  const argvs = process.argv.slice(2);
  const parsed = {
    languages: [] as string[],
    translateCsv: path.resolve(cwd, 'intl/translate.csv'),
    inputDirs: [] as string[],
  };
  for (let i = 0; i < argvs.length; i++) {
    const key = argvs[i];
    if (key === '--lang' || key === '-l') {
      parsed.languages = argvs[i + 1].split(',');
    } else if (key === '--csv' || key === '-c') {
      parsed.translateCsv = path.resolve(cwd, argvs[i + 1]);
    } else {
      parsed.inputDirs.push(path.resolve(cwd, key));
      continue;
    }
    i += 1; // skip value index
  }
  if (!parsed.languages.length) {
    console.error('missing --lang parameter');
    process.exit(-1);
  }
  if (!parsed.inputDirs.length) {
    parsed.inputDirs.push(path.resolve(cwd, 'src'));
  }
  return parsed;
}

export function parseCompileArgvs() {
  const cwd = process.cwd();
  const argvs = process.argv.slice(2);
  const parsed = {
    translateCsv: path.resolve(cwd, 'intl/translate.csv'),
    outputDir: path.resolve(cwd, 'intl'),
  };
  for (let i = 0; i < argvs.length; i++) {
    const key = argvs[i];
    if (key === '--csv' || key === '-c') {
      parsed.translateCsv = path.resolve(cwd, argvs[i + 1]);
    } else if (key === '--output-dir' || key === '-o') {
      parsed.outputDir = path.resolve(cwd, argvs[i + 1]);
    } else {
      continue;
    }
    i += 1; // skip value index
  }

  return parsed;
}

export async function loopMkdir(dir: string) {
  const pdir = path.dirname(dir);
  try {
    const st = await fs.stat(pdir);
    if (!st.isDirectory()) throw new Error(`${pdir} is not directory`);
  } catch (ex) {
    if ((ex as { code: string }).code === 'ENOENT') {
      await loopMkdir(pdir);
    } else {
      throw ex;
    }
  }
  try {
    await fs.mkdir(dir);
  } catch (ex) {
    if ((ex as { code: string }).code !== 'EEXIST') throw ex;
  }
}

const fileCheckers = new WeakMap<ts.SourceFile, ts.TypeChecker>();
function getFileChecker(srcFile: ts.SourceFile) {
  let checker = fileCheckers.get(srcFile);
  if (!checker) {
    const options = { noLib: true, noResolve: true };
    const host = ts.createCompilerHost(options);
    host.getSourceFile = (file) => (file === srcFile.fileName ? srcFile : undefined);
    checker = ts.createProgram([srcFile.fileName], options, host).getTypeChecker();
    fileCheckers.set(srcFile, checker);
  }
  return checker;
}

// Only direct named imports from jinge participate; never resolve re-exports.
const fileIntlImports = new WeakMap<ts.SourceFile, Map<string, ts.ImportSpecifier>>();
function isIntlT(id: ts.Identifier, srcFile: ts.SourceFile): boolean {
  let imports = fileIntlImports.get(srcFile);
  if (!imports) {
    imports = new Map();
    for (const statement of srcFile.statements) {
      if (
        !ts.isImportDeclaration(statement) ||
        !ts.isStringLiteral(statement.moduleSpecifier) ||
        statement.moduleSpecifier.text !== 'jinge'
      )
        continue;
      const clause = statement.importClause;
      if (
        !clause ||
        clause.isTypeOnly ||
        !clause.namedBindings ||
        !ts.isNamedImports(clause.namedBindings)
      )
        continue;
      for (const specifier of clause.namedBindings.elements) {
        if (!specifier.isTypeOnly && (specifier.propertyName ?? specifier.name).text === 't')
          imports.set(specifier.name.text, specifier);
      }
    }
    fileIntlImports.set(srcFile, imports);
  }
  const imported = imports.get(id.text);
  if (!imported) return false;
  const checker = getFileChecker(srcFile);
  const symbol = checker.getSymbolAtLocation(id);
  return symbol !== undefined && symbol === checker.getSymbolAtLocation(imported.name);
}

export interface ExtractMessage {
  key: string;
  defaultMessage: string;
  richComps?: Set<string>;
}
/**
 *
 * @param node AST 节点
 * @param mode 提取模式。extract 模式用于 intl-extract ，提取 t() 函数的 defaultMessage 并计算 key。
 * compile 模式用于 intl-compile，提取 t() 的 defaultMessage 和 params 中可用的富文本标签名，计算 key；不复制组件或回调实现。
 */
export function extractKeyAndMessage(
  filename: string,
  node: ts.Node,
  mode: 'extract' | 'compile',
  srcFile: ts.SourceFile,
): ExtractMessage | null {
  validateSourceNames(srcFile);
  if (
    !ts.isCallExpression(node) ||
    !ts.isIdentifier(node.expression) ||
    !isIntlT(node.expression, srcFile)
  ) {
    return null;
  }

  const params = node.arguments.at(1);
  let richComps: Set<string> | undefined;
  if (mode === 'compile') {
    if (!params || !ts.isObjectLiteralExpression(params)) {
      return null; // compile 模式下，如果没有 params 参数或参数不是 object，忽略。
    }
    for (const prop of params.properties) {
      if (!ts.isPropertyAssignment(prop)) continue;
      if (!ts.isIdentifier(prop.name) && !ts.isStringLiteral(prop.name)) continue;
      const expr = prop.initializer;
      if (
        ts.isJsxSelfClosingElement(expr) ||
        ts.isJsxElement(expr) ||
        ts.isJsxFragment(expr) ||
        ts.isArrowFunction(expr) ||
        ts.isFunctionExpression(expr)
      ) {
        // Only tag availability is extracted. Implementations stay at the call site.
        richComps ??= new Set();
        richComps.add(prop.name.text);
      }
    }
    if (!richComps?.size) return null;
  }

  const defaultText = node.arguments.at(0);
  if (!defaultText || !ts.isStringLiteral(defaultText)) {
    const { line, character } = ts.getLineAndCharacterOfPosition(srcFile, node.expression.getEnd());
    console.error(`t函数缺失默认语言文案。\n  --> ${filename}:${line + 1}:${character}`);
    process.exit(-1);
  }

  if (mode === 'extract') {
    if (params) {
      if (!defaultText.text.includes('{') && !/<[A-Za-z][\w-]*\s*\/?>/.test(defaultText.text)) {
        const { line, character } = ts.getLineAndCharacterOfPosition(srcFile, params.pos);
        console.error(
          `t函数如果指定了数据参数，则默认文案中必须使用参数。\n  --> ${filename}:${line + 1}:${character}`,
        );
        process.exit(-1);
      }
    }
  }

  const options = node.arguments.at(2);
  let key = '';
  if (options && ts.isObjectLiteralExpression(options)) {
    for (const prop of options.properties) {
      if (!ts.isPropertyAssignment(prop)) continue;
      if (!ts.isIdentifier(prop.name)) continue;
      if (prop.name.text === 'key') {
        if (ts.isStringLiteral(prop.initializer)) {
          key = prop.initializer.text.trim();
        }
        break;
      }
    }
  }

  const defaultMessage = defaultText.text;
  if (!key) key = calcIntlTextKey(defaultMessage);

  return { key, defaultMessage, richComps };
}
